import {mkdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const output='../benchmarks/results/notes-editor';
await mkdir(output,{recursive:true});
let note={note_id:'editor-check',note_type:'freeform',source_type:'scope',source_ref:'test',source_title:'Research notes',title:'Attention and representation',body_md:'A key finding about attention.',selected_text:'',tags:[],folder_id:'default',attachments:[],updated_at:new Date().toISOString(),notion_page_id:'',notion_dirty:false};
const browser=await chromium.launch({headless:true});
const errors=[];
let page;
try {
  page=await browser.newPage({viewport:{width:1440,height:1050}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.route(/\/api\/|127\.0\.0\.1:8002\//,async route=>{
    const p=new URL(route.request().url()).pathname.replace(/^\/api/, '');
    let body={};
    if(p==='/health') body={status:'ok'};
    else if(p==='/notes/editor-check' && route.request().method()==='PATCH') {note={...note,...route.request().postDataJSON()};body={note};}
    else if(p==='/notes') body={notes:[note]};
    else if(p==='/notes/folders') body={folders:[{folder_id:'default',name:'All notes'}]};
    else if(p==='/notes/notion/targets') body={targets:[]};
    else if(p==='/notes/migrate-workspace') body={imported:0};
    else if(p==='/articles') body={articles:[]};
    else if(p==='/articles/domains') body={domains:[]};
    else if(p==='/clusters') body={clusters:[],documents:[]};
    else if(p==='/chat/sessions') body={sessions:[]};
    else if(p==='/agent/sessions') body={sessions:[]};
    await route.fulfill({json:body});
  });
  await page.goto(`${process.env.APP_URL || 'http://127.0.0.1:5175'}/app`);
  await page.locator('.rm-nav-button').filter({hasText:/^Notes$/}).click();
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Edit research note',exact:true});
  const editor=dialog.getByRole('textbox',{name:'Note document',exact:true});
  await editor.evaluate(el=>{
    const text=el.querySelector('p').firstChild;
    const range=document.createRange();range.setStart(text,2);range.setEnd(text,13);
    const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);el.focus();
  });
  await dialog.getByRole('button',{name:'Highlight text',exact:true}).click();
  assert.equal(await editor.locator('mark').innerText(),'key finding');
  await dialog.getByRole('button',{name:'Bold (Ctrl+B)',exact:true}).click();
  assert.equal(await editor.locator('strong').innerText(),'key finding');
  await editor.press('ArrowRight');
  await editor.press('End');
  await dialog.getByRole('button',{name:'Insert formula',exact:true}).click();
  const formula=page.getByRole('dialog',{name:'LaTeX formula',exact:true});
  await formula.getByLabel('LaTeX source',{exact:true}).fill('\\frac{');
  assert.equal(await formula.getByRole('button',{name:'Apply formula'}).isDisabled(),true);
  await formula.getByLabel('LaTeX source',{exact:true}).fill('\\frac{QK^T}{\\sqrt{d_k}}');
  await formula.getByLabel('Display on its own line').check();
  await page.screenshot({path:output+'/formula-dialog.png'});
  await formula.getByRole('button',{name:'Apply formula'}).click();
  await editor.locator('[data-type="block-math"]').waitFor();
  await editor.locator('[data-type="block-math"]').click();
  assert.equal(await formula.getByLabel('LaTeX source',{exact:true}).inputValue(),'\\frac{QK^T}{\\sqrt{d_k}}');
  await formula.getByRole('button',{name:'Apply formula'}).click();
  await dialog.getByTitle('Edit Markdown and LaTeX source').click();
  const source=dialog.getByRole('textbox',{name:'Markdown and LaTeX source'});
  const edited=await source.inputValue();
  assert.ok(edited.includes('==') && edited.includes('**') && edited.includes('\\frac'));
  const sample='# Attention and representation\n\nA ==**key finding**==: attention lets each token use context.\n\n## Scaled dot-product attention\n\nFor a key dimension $d_k$, we compute:\n\n$$\n\\operatorname{Attention}(Q,K,V) = \\operatorname{softmax}\\left(\\frac{QK^T}{\\sqrt{d_k}}\\right)V\n$$\n\n## Reading notes\n\n- ++Query and key dimensions must agree.++\n- Compare the result with the unscaled baseline.\n\n> Why does scaling stabilize the softmax?\n\n$$\n\\begin{bmatrix}0.8 & 0.2 \\\\ 0.1 & 0.9\\end{bmatrix}\n$$';
  await source.fill(sample);
  await page.screenshot({path:output+'/source-preview.png'});
  await dialog.getByTitle('Edit Markdown and LaTeX source').click();
  assert.equal(await editor.locator('.katex').count(),3);
  await page.screenshot({path:output+'/document-desktop.png'});
  await dialog.getByRole('button',{name:'Save changes'}).click();
  assert.equal(note.body_md,sample);
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  assert.equal(await editor.locator('.katex').count(),3);
  assert.equal(await editor.locator('mark').innerText(),'key finding');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:output+'/document-mobile.png',animations:'disabled'});
  const overflow=await dialog.evaluate(el=>el.scrollWidth>el.clientWidth+2);
  assert.equal(overflow,false,'Editor dialog overflows narrow screen');
  assert.deepEqual(errors,[]);
  await writeFile(output+'/checks.json',JSON.stringify({highlight:true,bold:true,formulaValidation:true,formulaEditing:true,sourcePreview:true,savedAndReopened:true,mobileOverflow:overflow,errors},null,2));
  console.log('PASS: highlight, bold, formula insertion/editing, source preview, save/reopen, narrow screen; no page errors.');
} catch(error) {
  console.log('Browser errors:',errors);
  console.log((await page?.locator('body').innerText())?.slice(0,1400));
  await page?.screenshot({path:output+'/failure.png'});
  throw error;
} finally {await browser.close();}
